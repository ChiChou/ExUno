import Foundation

/// One fill-in-the-blank item from a grammar course (compact keys, like the vocabulary packs).
struct GrammarItem: Codable, Hashable {
    let x: String          // sentence with "___" for the gap
    let a: String          // answer, spelled as in the sentence
    let o: [String]        // options, answer included
    let e: String          // English translation
    var h: String?         // lemma hint
    let g: String          // label of the answer's cell ("presente · io", "sg. · acc.")
    let k: String          // "<row id>/<column index>"

    static let gap = "___"

    var before: String { x.components(separatedBy: Self.gap).first ?? x }
    var after: String { x.components(separatedBy: Self.gap).dropFirst().joined(separator: Self.gap) }
    func filled(with option: String) -> String { before + option + after }
    var sentence: String { filled(with: a) }
    var row: String { String(k.split(separator: "/").first ?? "") }
    var column: Int? { k.split(separator: "/").last.flatMap { Int($0) } }
}

struct GrammarTable: Codable, Hashable {
    let cols: [String]
    let rows: [[String]]
}

struct GrammarUnit: Codable, Identifiable, Hashable {
    let id: String
    let level: String
    let title: String
    let en: String
    let note: String
    var table: GrammarTable?
    let items: [GrammarItem]

    static func == (a: GrammarUnit, b: GrammarUnit) -> Bool { a.id == b.id }
    func hash(into hasher: inout Hasher) { hasher.combine(id) }
}

struct GrammarCourseFile: Codable {
    let code: String
    let schema: Int
    let license: String
    let attribution: String
    let levels: [String]
    let units: [GrammarUnit]
}

/// Loads the grammar course for the study language (generated by Scripts/build_grammar.py).
@Observable
final class GrammarCourses {
    private(set) var current: GrammarCourseFile?
    private(set) var missing = false
    @ObservationIgnored private var cache: [LanguageCode: GrammarCourseFile] = [:]

    var units: [GrammarUnit] { current?.units ?? [] }

    func load(_ code: LanguageCode) {
        if let c = cache[code] { current = c; missing = false; return }
        current = nil
        missing = false
        Task.detached(priority: .utility) {
            let name = "grammar-\(code.rawValue)"
            let url = Bundle.main.url(forResource: name, withExtension: "json", subdirectory: "Packs") ?? Bundle.main.url(forResource: name, withExtension: "json")
            let file = url.flatMap { try? Data(contentsOf: $0) }.flatMap { try? JSONDecoder().decode(GrammarCourseFile.self, from: $0) }
            await MainActor.run {
                if let file { self.cache[code] = file; self.current = file } else { self.missing = true }
            }
        }
    }
}

// MARK: - Practice

/// Best result and how far the rotation through a unit's items has got.
struct LessonScore: Codable, Equatable {
    var best = 0
    var runs = 0
    var lastDay = 0

    static let passMark = 8

    var passed: Bool { best >= Self.passMark }

    func merged(with other: LessonScore) -> LessonScore {
        LessonScore(best: max(best, other.best), runs: max(runs, other.runs), lastDay: max(lastDay, other.lastDay))
    }
}

/// One practice round: ten items, rotating through the unit so repeated runs show new sentences.
struct GrammarRound: Equatable {
    static let size = 10
    let items: [GrammarItem]
    private(set) var index = 0
    private(set) var correct = 0
    private(set) var chosen: String?

    init(unit: GrammarUnit, run: Int) {
        let all = unit.items
        guard !all.isEmpty else { items = []; return }
        let n = min(Self.size, all.count)
        let start = (run * Self.size) % all.count
        items = (0..<n).map { all[(start + $0) % all.count] }
    }

    var current: GrammarItem? { items[safe: index] }
    var isFinished: Bool { index >= items.count }
    var answered: Bool { chosen != nil }
    var wasCorrect: Bool { chosen != nil && chosen == current?.a }

    /// Records the first choice for the current item; later taps are ignored until `advance()`.
    @discardableResult
    mutating func choose(_ option: String) -> Bool {
        guard let item = current, chosen == nil else { return false }
        chosen = option
        if option == item.a { correct += 1 }
        return option == item.a
    }

    mutating func advance() {
        guard chosen != nil else { return }
        chosen = nil
        index += 1
    }
}

extension StudyProgress {
    func lessonScore(_ unitID: String) -> LessonScore { pack.grammar?[unitID] ?? LessonScore() }

    /// Counts a grammar answer as a review for the day, like the real-life cards.
    func logGrammarAnswer(correct: Bool) {
        let d = Self.today()
        var l = pack.log[d] ?? DayLog()
        l.reviews += 1
        if correct { l.good += 1 } else { l.again += 1 }
        pack.log[d] = l
    }

    func finishLesson(_ unitID: String, correct: Int) {
        var all = pack.grammar ?? [:]
        var s = all[unitID] ?? LessonScore()
        s.best = max(s.best, correct)
        s.runs += 1
        s.lastDay = Self.today()
        all[unitID] = s
        pack.grammar = all
    }
}

/// Labels for the grammar screens in the study language.
struct GrammarStrings {
    var grammar, course, practice, rule, again, passed: String
    var lessons: (Int, Int) -> String

    static func `for`(_ code: LanguageCode) -> GrammarStrings {
        switch code {
        case .it: return GrammarStrings(grammar: "Grammatica", course: "Corso di grammatica", practice: "Esercitati", rule: "La regola", again: "Ancora",
                                        passed: "Superata", lessons: { "\($0) di \($1) lezioni" })
        case .es: return GrammarStrings(grammar: "Gramática", course: "Curso de gramática", practice: "Practicar", rule: "La regla", again: "Otra vez",
                                        passed: "Superada", lessons: { "\($0) de \($1) lecciones" })
        case .fr: return GrammarStrings(grammar: "Grammaire", course: "Cours de grammaire", practice: "S'entraîner", rule: "La règle", again: "Encore",
                                        passed: "Réussie", lessons: { "\($0) leçons sur \($1)" })
        case .pt: return GrammarStrings(grammar: "Gramática", course: "Curso de gramática", practice: "Praticar", rule: "A regra", again: "Outra vez",
                                        passed: "Concluída", lessons: { "\($0) de \($1) lições" })
        case .la: return GrammarStrings(grammar: "Grammatica", course: "Cursus grammaticus", practice: "Exercē", rule: "Rēgula", again: "Iterum",
                                        passed: "Perfecta", lessons: { "\($0) ex \($1) lēctiōnibus" })
        }
    }
}
